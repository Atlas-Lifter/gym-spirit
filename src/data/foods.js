// 음식 특징 표시: 100g 기준 칼로리 중 단백질 비율 등으로 판단
export const foodTags = (f) => {
  const tags = [];
  if (f.calories > 0 && (f.protein * 4) / f.calories >= 0.35 && f.protein >= 5) tags.push('고단백');
  if (f.calories <= 60 && f.unit === 'g') tags.push('저칼로리');
  if (f.calories >= 350) tags.push('고칼로리');
  if (f.fat >= 15 && f.category !== '지방') tags.push('지방 많음');
  return tags;
};
